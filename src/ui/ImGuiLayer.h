#pragma once
/**
 * @file ImGuiLayer.h
 * @brief Обёртка для инициализации и кадро-управления Dear ImGui в связке с GLFW + OpenGL.
 *
 * Класс инкапсулирует типовой жизненный цикл ImGui:
 * - Init() — однократная инициализация контекста и backend-ов (GLFW/OpenGL).
 * - BeginFrame() — начало кадра (NewFrame для всех слоёв ImGui).
 * - (опц.) DrawDockspace() — отрисовка корневого док-пространства.
 * - EndFrame() — рендер и представление результата в текущий OpenGL-контекст.
 * - Shutdown() — корректное завершение работы и освобождение ресурсов.
 *
 * Замечания:
 * - Класс **не владеет** окном GLFW — переданный указатель должен быть валиден
 *   на протяжении всего жизненного цикла слоя.
 * - Все вызовы следует выполнять из **главного UI-потока** (там, где активен контекст OpenGL).
 * - Параметр `glsl` должен соответствовать версии шейдеров, поддерживаемой вашим контекстом.
 */

struct GLFWwindow;

namespace ui {

/**
 * @class ImGuiLayer
 * @brief Сервисный слой для интеграции Dear ImGui с GLFW/OpenGL.
 */
class ImGuiLayer {
 public:
  /**
   * @brief Инициализация Dear ImGui и backend-ов (GLFW + OpenGL3).
   *
   * Вызывается один раз после создания окна и контекста OpenGL.
   * Создаёт контекст ImGui, настраивает стиль, подключает платформенный
   * и рендер-бекенды, включает докинг/мульти-вьюпорт при необходимости.
   *
   * @param window Указатель на активное окно GLFW (не владение).
   * @param glsl   Строка с версией GLSL для рендер-бекенда ImGui.
   *               По умолчанию `"#version 330"` (Core profile).
   *
   * @note Контекст OpenGL должен быть **активен** для `window` во время вызова.
   * @throws Может пробросить std::runtime_error при ошибке инициализации.
   */
  void Init(GLFWwindow* window, const char* glsl = "#version 330");

  /**
   * @brief Полная очистка ресурсов ImGui.
   *
   * Отключает рендер- и платформ-бекенды, уничтожает контекст ImGui.
   * Вызывать перед уничтожением окна/контекста OpenGL.
   * Повторные вызовы безопасны (no-op после первого завершения).
   */
  void Shutdown();

  /**
   * @brief Начало кадра ImGui.
   *
   * Должно вызываться ровно один раз в кадре **до** всех вызовов ImGui API.
   * Выполняет `ImGui::NewFrame()` для платформенного и рендер-бекендов.
   */
  void BeginFrame();

  /**
   * @brief Завершение кадра ImGui и рендер в текущий кадр OpenGL.
   *
   * Должно вызываться один раз в конце кадра, **после** всей отрисовки UI.
   * Выполняет `ImGui::Render()` и отправляет команды в OpenGL через backend.
   */
  void EndFrame();

  /**
   * @brief Отрисовка док-пространства на весь вьюпорт.
   *
   * Создаёт невидимое корневое окно без рамок и размещает в нём DockSpace,
   * чтобы можно было стыковать панели/окна ImGui по всей области.
   * Вызывать между `BeginFrame()` и `EndFrame()`.
   *
   * @note Если в проекте уже есть свой корневой DockSpace — этот метод не обязателен.
   */
  void DrawDockspace();
};

}  // namespace ui

